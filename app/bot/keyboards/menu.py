def online_menu(in_room: bool = False, admin: bool = False) -> InlineKeyboardMarkup:
    rows = []
    if in_room:
        rows.append([_btn("Вернуться в комнату", "online:resume")])
    else:
        rows.append([_btn("Создать комнату", "online:create")])
        rows.append([_btn("Войти по коду", "online:join")])
        if admin:
            rows.append([_btn("Тестовые лобби", "online:testmenu")])
    rows.append([_btn("Закрыть", "menu:home")])
    return InlineKeyboardMarkup(inline_keyboard=rows)


def back_menu() -> InlineKeyboardMarkup:
    return InlineKeyboardMarkup(inline_keyboard=[[_btn("Закрыть", "menu:home")]])
